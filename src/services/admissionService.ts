import { supabase } from '../lib/supabase'

// ─── Matric number format engine (§7.27.1/§12, PRD SESSION 65) ────────────
// The format is fully admin-configurable per school, not fixed to one
// pattern: an ordered list of components, each carrying its own preceding
// separator, matching real Nigerian institutional practice (component
// choice/ordering/separators all genuinely differ by institution —
// researched before assuming otherwise, §12 decision 2026-07-17). The actual
// generation happens server-side (build_matric_number(),
// migration_session_65.sql/65b.sql) so this file only reads/writes the
// format definition itself — it never assembles a matric number
// client-side, which would duplicate logic the atomic admit_student()
// function already owns.
export type MatricNumberComponentType =
  | 'programme_code'
  | 'faculty_code'
  | 'department_code'
  | 'session_year'
  | 'constant'
  | 'sequence'

export interface MatricNumberComponent {
  type: MatricNumberComponentType
  separator: string | null        // printed immediately before this component; ignored on the first component in the list
  value?: string                  // 'constant' only — the free-text literal (e.g. a school abbreviation)
  year_format?: '2digit' | '4digit'  // 'session_year' only
  digits?: number                 // 'sequence' only — zero-padding width
}

export interface MatricNumberFormat {
  id: string
  components: MatricNumberComponent[]
  is_active: boolean
}

// Reads the school's currently *active* format only — the versioned history
// (inactive rows) is a deliberate non-goal for this function; nothing in the
// admission or settings UI currently needs to browse past versions, only to
// know "what will admit_student() use right now." A history view can be
// added later against the same table without any schema change, if wanted.
export async function loadMatricNumberFormat(
  schoolId: string,
): Promise<{ data: MatricNumberFormat | null; error: string | null }> {
  const { data, error } = await supabase
    .from('matric_number_formats')
    .select('id, components, is_active')
    .eq('school_id', schoolId)
    .eq('is_active', true)
    .maybeSingle()
  if (error) return { data: null, error: error.message }
  if (!data) return { data: null, error: null }  // not configured yet — a normal state, not an error, same convention loadCgpaPolicy() already established
  return {
    data: {
      id: (data as any).id,
      components: ((data as any).components ?? []) as MatricNumberComponent[],
      is_active: (data as any).is_active,
    },
    error: null,
  }
}

// True once any student has genuinely been admitted under this school's
// current format — i.e. the soft-lock's own trigger condition (§12 decision,
// 2026-07-17: "once matric_sequence_counters has any row with
// current_value > 0"). A cheap existence check, not a count — the caller
// only needs to know whether to show the warning, not by how much.
export async function hasAnyMatricAdmissions(
  schoolId: string,
): Promise<{ data: boolean; error: string | null }> {
  const { data, error } = await supabase
    .from('matric_sequence_counters')
    .select('id')
    .eq('school_id', schoolId)
    .gt('current_value', 0)
    .limit(1)
  if (error) return { data: false, error: error.message }
  return { data: (data ?? []).length > 0, error: null }
}

// Always inserts a new version — never updates a row in place. The caller
// (the admission UI's format editor) is responsible for surfacing the
// soft-lock warning via hasAnyMatricAdmissions() *before* calling this, since
// this function itself does not block the save; per the §12 decision, a
// school legitimately fixing a mistake before real admissions ramp up still
// needs to be able to, just not casually/silently once real numbers exist.
// The previously-active row (if any) is flipped to is_active = false in the
// same operation, never deleted — that history is the entire point of the
// versioning correction.
export async function saveMatricNumberFormat(
  schoolId: string,
  components: MatricNumberComponent[],
): Promise<{ error: string | null }> {
  const { data: current, error: currentError } = await supabase
    .from('matric_number_formats')
    .select('id')
    .eq('school_id', schoolId)
    .eq('is_active', true)
    .maybeSingle()
  if (currentError) return { error: currentError.message }

  if (current) {
    const { error: deactivateError } = await supabase
      .from('matric_number_formats')
      .update({ is_active: false, updated_at: new Date().toISOString() })
      .eq('id', (current as any).id)
    if (deactivateError) return { error: deactivateError.message }
  }

  const { error: insertError } = await supabase
    .from('matric_number_formats')
    .insert({ school_id: schoolId, components, is_active: true })
  return { error: insertError?.message ?? null }
}

// ─── Admission (§7.27.1a, PRD SESSION 65) ──────────────────────────────────
// The real, atomic admission operation this session's card exists to build —
// replaces the previous two disconnected manual steps (create the student
// via StudentsModule's own Add form, then separately place them via
// settingsService.ts's upsertPlacement() with a hand-typed matric number,
// SESSION 55's own Done Check). Calls a security-definer Postgres function
// (admit_student(), migration_session_65.sql/65b.sql) rather than doing the
// counter-increment + student-update + placement-insert as three separate
// client calls, specifically because the sequence counter must be
// incremented atomically under concurrent admissions (§12 decision,
// 2026-07-17) — reading-then-incrementing a counter from the client is a
// real race two admins hitting "Admit" for the same programme/year at the
// same moment could hit; upsertPlacement()'s own client-side
// demote-then-insert is fine for a placement alone, but not for a value that
// must never repeat.
export interface AdmitStudentResult {
  matric_number: string
  placement_id: string
  // false when the selected student already had a matric_number (a
  // re-placement into a new programme/level, not a first admission) — the
  // existing number was reused rather than a second one generated, and
  // matric_number_format_id is deliberately NOT touched on this branch. True
  // on a genuine first admission.
  generated_new_number: boolean
}

export async function admitStudent(params: {
  schoolId: string
  studentId: string
  programmeLevelId: string
  sessionId: string
  admissionYear: number
}): Promise<{ data: AdmitStudentResult | null; error: string | null }> {
  const { data, error } = await supabase.rpc('admit_student', {
    p_school_id: params.schoolId,
    p_student_id: params.studentId,
    p_programme_level_id: params.programmeLevelId,
    p_session_id: params.sessionId,
    p_admission_year: params.admissionYear,
  })
  if (error) return { data: null, error: friendlyAdmitError(error.message) }
  // Postgres RETURNS TABLE functions come back as an array of rows via
  // .rpc() — exactly one row here since admit_student() either returns one
  // row or raises.
  const row = Array.isArray(data) ? data[0] : data
  if (!row) return { data: null, error: 'Admission did not return a result.' }
  return {
    data: {
      matric_number: row.matric_number,
      placement_id: row.placement_id,
      generated_new_number: row.generated_new_number,
    },
    error: null,
  }
}

// Maps admit_student()'s real raised exceptions to plain-English copy,
// matching settingsService.ts's own friendlyError()-family convention rather
// than surfacing a raw Postgres message. Copy updated to point at the new
// admission screen's own format-setup entry point, not Settings → Institution
// (that entry point moved along with everything else in this file).
function friendlyAdmitError(message: string): string {
  if (message.includes('No matric number format configured')) {
    return 'This school has no matric number format set up yet. Configure one before admitting a student.'
  }
  if (message.includes('Not authorized')) {
    return 'You do not have permission to admit students.'
  }
  if (message.includes('Programme level not found')) {
    return 'That programme level could not be found. Refresh and try again.'
  }
  if (message.includes('Student not found')) {
    return 'That student could not be found for this school. Refresh and try again.'
  }
  return message
}
