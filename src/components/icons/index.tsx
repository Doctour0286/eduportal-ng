interface IconProps extends SVGProps<SVGSVGElement> {
  name: IconName
  /** Pixel size applied to both width and height. Defaults to 20. */
  size?: number
}

export function Icon({ name, size = 20, ...props }: IconProps) {
  const inner = ICONS[name]
  if (!inner) {
    // IconName is a closed union, so this only fires if a caller casts past
    // the type (e.g. a dynamic string). Warn rather than silently render
    // nothing, so a bad name is caught instead of shipping a blank space.
    console.warn(`Icon: unknown icon name "${name}"`)
    return null
  }
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...props}
    >
      {inner}
    </svg>
  )
}
